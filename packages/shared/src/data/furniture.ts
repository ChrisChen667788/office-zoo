/**
 * v0.6.0 Room Furniture Catalog
 *
 * Each room has 3-6 pieces of furniture placed at fixed logical-world
 * coordinates inside the room rect (defined in `types/game.ts`).
 *
 * Why a static catalog and not procedurally placed:
 *   - Hand-tuned layout reads as "real office" instead of "random debris"
 *   - Stable positions let agents target specific items deterministically
 *     (Frank always sits at desk_dev_1 → his "work" caption can reference
 *     it consistently, future v0.6.1 lets us anchor the player avatar
 *     beside the furniture instead of the room centre)
 *   - Same data drives both the canvas render (sprite + label) and the
 *     activity-aware caption layer ("Frank 在 工位3 改 PPT")
 *
 * Design constraints used during placement:
 *   - Furniture must sit fully inside its room rect (no overlap with
 *     walls or doors). Use 16-24 px padding from room edges.
 *   - Same-type items in the same room get a `_1`/`_2` suffix so player
 *     captions can disambiguate ("工位 1" vs "工位 2").
 *   - Sizes are visual hints only — collision / pathfinding ignores them
 *     in v0.6.0 (planned for v0.6.2 with A* re-plan around furniture).
 */

