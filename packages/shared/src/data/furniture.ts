export type FurnitureKind = keyof typeof FURNITURE_TYPES;

/** A single placed instance. Coordinates are absolute in the same logical
 *  world space as `PlayerPosition` (0..MAP_W × 0..MAP_H). */
export interface FurnitureItem {
  /** Stable id, used in captions + future agent targeting. Convention:
   *  `<kind>_<roomShortId>_<n>` so "desk_dev_1" reads as "工位 1 in 产品部". */
  id: string;
  kind: FurnitureKind;
  roomId: string;
  x: number;
  y: number;
  /** Optional human label override. Defaults to "<cnLabel> N" computed
   *  from `kind`'s catalogue entry + the item's index in its room. */
  label?: string;
}

/** Compute a placement helper — returns N evenly-spaced points along a
 *  horizontal axis inside the given rect, with edge padding. */
function placeRow(rect: RoomRect, count: number, yOffset: number, padding = 28): Array<{ x: number; y: number }> {
  const inner = rect.w - padding * 2;
  const step = count > 1 ? inner / (count - 1) : 0;
  const out: Array<{ x: number; y: number }> = [];
  for (let i = 0; i < count; i++) {
    out.push({
      x: rect.x + padding + step * i,
      y: rect.y + yOffset,
    });
  }
  return out;
}

function room(id: string): RoomRect {
  const r = ROOM_RECTS.find((rr) => rr.id === id);
  if (!r) throw new Error(`Unknown room: ${id}`);
  return r;
}

