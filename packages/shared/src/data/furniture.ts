// ---------------------------------------------------------------------------
// Lookup helpers — both sides import these. Pure, side-effect-free.
// ---------------------------------------------------------------------------

export function furnitureInRoom(roomId: string): FurnitureItem[] {
  return ROOM_FURNITURE.filter((f) => f.roomId === roomId);
}

/** Return the closest furniture item to a player position within `maxDist`
 *  logical pixels, or null if none qualify. Used by the server to upgrade
 *  generic "work" activities into "work@desk_dev_3" style captions, and by
 *  the client to highlight the focused item with a soft ring. */
export function nearestFurniture(
  roomId: string,
  px: number,
  py: number,
  maxDist = 60,
): FurnitureItem | null {
  let best: FurnitureItem | null = null;
  let bestSq = maxDist * maxDist;
  for (const f of ROOM_FURNITURE) {
    if (f.roomId !== roomId) continue;
    const def = FURNITURE_TYPES[f.kind];
    const cx = f.x + def.w / 2;
    const cy = f.y + def.h / 2;
    const dx = cx - px;
    const dy = cy - py;
    const d = dx * dx + dy * dy;
    if (d < bestSq) {
      bestSq = d;
      best = f;
    }
  }
  return best;
}

/** Render-friendly label for an item — "工位 3" etc. Server uses this to
 *  generate activity captions, client uses it for hover tooltips. */
export function labelFor(item: FurnitureItem): string {
  if (item.label) return item.label;
  const def = FURNITURE_TYPES[item.kind];
  // Number same-kind items within a room: "工位 1", "工位 2"...
  const sameKindInRoom = ROOM_FURNITURE
    .filter((f) => f.roomId === item.roomId && f.kind === item.kind);
  if (sameKindInRoom.length <= 1) return def.cnLabel;
  const idx = sameKindInRoom.findIndex((f) => f.id === item.id);
  return `${def.cnLabel} ${idx + 1}`;
}
