/**
 * Get a random item from an array
 */
export function randomJargon<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * Generate a random workplace buzzword sentence
 */
export function generateBuzzwordSentence(): string {
  const verb = randomJargon(JARGON_VERBS);
  const modifier = randomJargon(JARGON_MODIFIERS);
  const noun = randomJargon(JARGON_NOUNS);
  return `${modifier}${verb}${noun}`;
}
